-- =============================================================
-- ПРИМЕР: Вариация врага из внешнего аддона
-- Путь: addons/my_addon/lua/horde/modules/enemies/my_variation.lua
-- =============================================================
-- Вариация НЕ создаёт нового врага в пуле волн — она подменяет уже
-- существующего врага при спавне (с шансом и по условию). Спавн-конфиг
-- (сложность/волна/вес) наследуется от родителя, поэтому ParentEntity
-- указывается по КЛАССУ сущности родителя.
-- =============================================================

HORDE:RegisterEnemyVariation({
    -- Какой враг заменяется (класс сущности, а не Name конфига)
    ParentEntity = "npc_vj_horde_lesion",

    -- Новый враг
    Name         = "Build Buster",
    Class        = "npc_vj_horde_build_buster",

    -- Доля спавнов родителя (0..1). Можно числом (постоянная) или функцией
    -- function(enemy) return chance end — тогда она считается заново на каждый
    -- спавн, что нужно для доли, зависящей от состава игроков.
    -- Доли всех вариаций одного родителя складываются, остаток до 100%
    -- достаётся базовому врагу; порядок регистрации на доли не влияет.
    Chance       = 0.05,

    -- Необязательное условие (сервер). nil/false = не срабатывает.
    Condition    = function(enemy)
        return HORDE:CountClassPlayers(HORDE.Class_Engineer) > 0
    end,

    -- Где и с какой волны вариацию вообще можно встретить. Без этого поля —
    -- на любой сложности и с первой волны.
    Appearance   = {
        -- Семейство сложностей по цепочке Include (Include/Inherit/Base/
        -- Extends/Parent): строка или список имён. Сложность аддона с
        -- Include = "CHAOS" попадёт в это семейство автоматически.
        BasedOn      = "CHAOS",
        -- Минимальная волна для всего семейства (HORDE.current_wave).
        SinceWave    = 0,
        -- Точечные правила по имени сложности: значение — минимальная волна
        -- (true — с первой, false/nil — никогда). Важнее семейства.
        Difficulties = { HUNDRED = 20, UNARMED = 10 },
    },

    -- Необязательные оверрайды поверх копии конфига родителя.
    -- Те же поля, что у ENEMY: HealthScale / DamageScale / RewardScale /
    -- ModelScale / Color / Weapon / Mutation / SpawnLimit / ...
    Overrides    = { RewardScale = 2 },
})
