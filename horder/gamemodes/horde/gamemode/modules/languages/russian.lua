# Horde: REDUX - Выживание в волнах
Пройди все волны в игре и убей боссов чтобы победить.
За убийства врагов дают деньги. Их можно тратить в магазине ({shop} по умолчанию) на: Оружие, Патроны, Гаджеты и многое другое. Обычно магазин можно увидеть по особому значку на карте.

# Классы и прогрессия
В магазине можно выбрать класс. У каждого класса свой стартовый набор и своё древо навыков.
Навыки открываются по тирам и по мере роста уровня во время матча. Выбирай те, что больше подходят
твоему билду.

У некоторых классов есть базовая способность ({perk} по умолчанию) применяй её с умом.
Гаджеты - это активируемые бонусные способности, покупаемые в магазине, либо выпадающие с боссов
({gadget} по умолчанию)
Магические классы кастуют вспомогательное заклинание ({spell_f} по умолчанию) и ультимативное ({spell_r} по умолчанию).

# Враги
Враги появляются при начале волны, каждый из них даёт опыт и деньги при убийстве.
Враги разделены на 3 категории: Обычный, Элитный и Босс.
Элитные враги сильнее обычных, у них больше здоровья и есть особые способности. При их убийстве даётся больше опыта и есть небольшой шанс выпадения черепов.
Босс это особый враг, обычно появляющийся на каждой пятой волне. Это элитный враг, у которого по особенному много здоровья и его убийство завершает волну/матч.
Почти у каждого врага есть мутации - это особые бонусы для врагов, которые улучшают их силу против вас.

# Волны
Перед стартом игры и между волнами даётся передышка на магазин. Нажми "Готов" ({ready} по умолчанию) - волна начнётся быстрее.
Количество волн устанавливается модификатором.
Модификаторы и Сложности игры выбираются голосованием - чем выше сложность, тем больше волн и врагов. (Напиши !rtv в чат чтобы сменить карту.)

# Управление
{stats} - Стартовое меню.
{control_menu} - Конфигуратор (Доступен только администраторам).
{shop} - Магазин.
{ready} - Готовность.
Любую Horde клавишу можно переназначить на вкладке "Клавиатура" (Сохраняется локально).
]==]

